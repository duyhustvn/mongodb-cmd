// GetProfile godoc
// @Summary     Lấy danh sách slow query từ system.profile
// @Description Truy vấn system.profile với nhiều tùy chọn lọc: collection, duration, thời gian, phân trang. Hỗ trợ chế độ unique để gom nhóm theo queryHash.
// @Tags        profile
// @Produce     json
// @Param       endpoint       query  string  true   "MongoDB host (ví dụ: 172.17.0.1:27017)"
// @Param       database       query  string  true   "Tên database"
// @Param       collection     query  string  false  "Lọc theo collection"
// @Param       duration       query  integer false  "Chỉ lấy query chậm hơn N ms"
// @Param       limit          query  integer false  "Số kết quả tối đa (mặc định 20)"
// @Param       offset         query  integer false  "Bỏ qua N kết quả đầu (phân trang)"
// @Param       order_by       query  string  false  "Field sắp xếp (mặc định: ts)"
// @Param       order_type     query  string  false  "asc hoặc desc (mặc định: desc)"
// @Param       unique         query  boolean false  "Gom nhóm theo queryHash, trả về thống kê"
// @Param       from           query  string  false  "RFC3339 — lấy từ thời điểm này (ví dụ: 2025-01-01T00:00:00Z)"
// @Param       to             query  string  false  "RFC3339 — lấy đến thời điểm này"
// @Param       ignore_hashes  query  string  false  "Bỏ qua những bản ghi có queryHash trong danh sách"
// @Success     200  {array}   map[string]interface{}
// @Failure     400  {object}  map[string]string
// @Failure     500  {object}  map[string]string
// @Router      /mongodb-cmd/profile [get]
func (inst *handler) GetProfile(c *gin.Context) {
	var query GetDatabaseProfileQuery

	if err := c.ShouldBindQuery(&query); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
		return
	}

	client, exists := inst.MongoClients[query.Endpoint]
	if !exists {
		c.JSON(http.StatusBadRequest, gin.H{"error": fmt.Sprintf("Endpoint %s not found or disconnected", query.Endpoint)})
		return
	}

	ctx, cancel := context.WithTimeout(c.Request.Context(), 10*time.Second)
	defer cancel()

	col := client.Database(query.Database).Collection("system.profile")

	filter := bson.M{} // Dùng bson.M cho Map không cần thứ tự
	if query.Collection != "" {
		filter["ns"] = fmt.Sprintf("%s.%s", query.Database, query.Collection)
	}
	if query.Duration != nil {
		filter["millis"] = bson.M{"$gt": *query.Duration}
	}

	if query.IgnoreHashes != "" {
		var ignoreHashes []string

		for _, hash := range strings.Split(query.IgnoreHashes, ",") {
			if trimmed := strings.TrimSpace(hash); trimmed != "" {
				ignoreHashes = append(ignoreHashes, trimmed)
			}
			if len(ignoreHashes) > 0 {
				filter["queryHash"] = bson.M{"$nin": ignoreHashes}
			}
		}
	}

	// Lọc theo thời gian trên field "ts" của system.profile
	if query.From != "" || query.To != "" {
		tsFilter := bson.M{}
		if query.From != "" {
			t, err := time.Parse(time.RFC3339, query.From)
			if err != nil {
				c.JSON(http.StatusBadRequest, gin.H{"error": "invalid from (expect RFC3339): " + err.Error()})
				return
			}
			tsFilter["$gte"] = t
		}
		if query.To != "" {
			t, err := time.Parse(time.RFC3339, query.To)
			if err != nil {
				c.JSON(http.StatusBadRequest, gin.H{"error": "invalid to (expect RFC3339): " + err.Error()})
				return
			}
			tsFilter["$lte"] = t
		}
		filter["ts"] = tsFilter
	}

	limit := int64(10000)
	if query.Limit != nil {
		limit = *query.Limit
	}
	offset := int64(0)
	if query.Offset != nil {
		offset = *query.Offset
	}

	sortField := "ts"
	if query.OrderBy != "" {
		sortField = query.OrderBy
	}

	sortDirection := -1
	if query.OrderType == "asc" {
		sortDirection = 1
	}

	isUnique := false
	if query.Unique != nil && *query.Unique {
		isUnique = true
	}

	if isUnique {
		// Dùng bson.D cho các operations yêu cầu tính thứ tự (như Pipeline)
		pipeline := mongo.Pipeline{
			{{Key: "$match", Value: filter}},
			// sort trước khi group
			{{Key: "$sort", Value: bson.D{{Key: sortField, Value: sortDirection}}}},
			// limit số lượng bản ghi trước khi group
			{{Key: "$limit", Value: limit}},
			{{Key: "$group", Value: bson.D{
				{Key: "_id", Value: "$queryHash"},
				{Key: "count", Value: bson.D{{Key: "$sum", Value: 1}}},
				{Key: "max_millis", Value: bson.D{{Key: "$max", Value: "$millis"}}},
				{Key: "avg_millis", Value: bson.D{{Key: "$avg", Value: "$millis"}}},
				{Key: "latest_ts", Value: bson.D{{Key: "$max", Value: "$ts"}}},
				{Key: "sample_ns", Value: bson.D{{Key: "$first", Value: "$ns"}}},
			}}},
			{{Key: "$sort", Value: bson.D{{Key: "count", Value: -1}}}}, // Xếp theo query xuất hiện nhiều nhất
			{{Key: "$skip", Value: offset}},
			{{Key: "$limit", Value: 5}}, // mặc định limit là 5
		}

		cursor, err := col.Aggregate(ctx, pipeline)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
			return
		}

		var results []bson.M
		if err = cursor.All(ctx, &results); err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
			return
		}

		if results == nil {
			results = []bson.M{}
		}
		c.JSON(http.StatusOK, results)

	} else {
		findOptions := options.Find().
			SetSort(bson.D{{Key: sortField, Value: sortDirection}}).
			SetLimit(limit).
			SetSkip(offset)

		cursor, err := col.Find(ctx, filter, findOptions)
		if err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
			return
		}

		var results []bson.M
		if err = cursor.All(ctx, &results); err != nil {
			c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
			return
		}

		if results == nil {
			results = []bson.M{}
		}
		c.JSON(http.StatusOK, results)
	}
}

// newStorageClient tạo MongoDB client để lưu snapshot.
// Nếu storage.uri được cấu hình thì dùng trực tiếp URI đó.
// Ngược lại, build multi-host URI từ mongodb config (RS-aware, không directConnection).
func newStorageClient(cfg *config.Config) (*mongo.Client, error) {
	var uri string
	if cfg.Storage.URI != "" {
		uri = cfg.Storage.URI
		log.Printf("Storage: using configured storage.uri")
	} else {
		hosts := strings.Split(cfg.Mongodb.Host, ",")
		var trimmedHosts []string
		for _, h := range hosts {
			h = strings.TrimSpace(h)
			if h != "" {
				trimmedHosts = append(trimmedHosts, h)
			}
		}
		if len(trimmedHosts) == 0 {
			return nil, fmt.Errorf("no valid mongodb hosts in config")
		}
		encodedUser := url.QueryEscape(cfg.Mongodb.Username)
		encodedPass := url.QueryEscape(cfg.Mongodb.Password)
		// Nối tất cả host → driver tự discover replica set, không dùng directConnection
		uri = fmt.Sprintf("mongodb://%s:%s@%s/", encodedUser, encodedPass, strings.Join(trimmedHosts, ","))
		log.Printf("Storage: using mongodb config hosts (%s)", strings.Join(trimmedHosts, ","))
	}

	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()

	clientOpts := options.Client().ApplyURI(uri)
	client, err := mongo.Connect(clientOpts)
	if err != nil {
		return nil, fmt.Errorf("storage connect error: %w", err)
	}
	if err := client.Ping(ctx, nil); err != nil {
		return nil, fmt.Errorf("storage ping error: %w", err)
	}
	log.Println("Successfully connected to storage MongoDB")
	return client, nil
}

