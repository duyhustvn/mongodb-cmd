// GetProfiles godoc
// @Summary     Đếm số slow query entries trong system.profile trên tất cả host
// @Description Trả về số lượng document trong system.profile của từng database trên mỗi MongoDB host đang giám sát.
// @Tags        profile
// @Produce     json
// @Param       databases  query  string  false  "Danh sách database cách nhau bằng dấu phẩy (bỏ trống = tất cả)"
// @Success     200  {object}  CountSystemProfileResponse
// @Failure     400  {object}  map[string]string
// @Router      /mongodb-cmd/profiles [get]
func (inst *handler) GetProfiles(c *gin.Context) {
	var query CountSystemProfileRequest
	if err := c.ShouldBindQuery(&query); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
		return
	}

	var results []CountSystemProfileResult = make([]CountSystemProfileResult, 0)

	// 1. Phân tách danh sách databases từ user (nếu có)
	var userDBs []string
	if query.Databases != "" {
		for _, db := range strings.Split(query.Databases, ",") {
			trimmed := strings.TrimSpace(db)
			if trimmed != "" {
				userDBs = append(userDBs, trimmed)
			}
		}
	}

	ctx, cancel := context.WithTimeout(c.Request.Context(), 30*time.Second)
	defer cancel()

	for host, client := range inst.MongoClients {
		targetDBs := userDBs

		if len(targetDBs) == 0 {
			dbNames, err := client.ListDatabaseNames(ctx, bson.M{})
			if err != nil {
				errMsg := err.Error()
				results = append(results, CountSystemProfileResult{
					URL:      host,
					Database: "",
					Count:    0,
					Error:    &errMsg,
				})
				continue // Chuyển sang server tiếp theo
			}
			targetDBs = dbNames
		}

		for _, dbName := range targetDBs {
			col := client.Database(dbName).Collection("system.profile")
			count, err := col.CountDocuments(ctx, bson.M{})

			if err != nil {
				errMsg := err.Error()
				results = append(results, CountSystemProfileResult{
					URL:      host,
					Database: dbName,
					Count:    0,
					Error:    &errMsg,
				})
			} else {
				results = append(results, CountSystemProfileResult{
					URL:      host,
					Database: dbName,
					Count:    count,
				})
			}
		}
	}

	c.JSON(http.StatusOK, CountSystemProfileResponse{Results: results})
}

